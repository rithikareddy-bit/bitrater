#!/usr/bin/env bash
# Assemble the Azure Functions package in azure-functions/:
#   orchestrator_src/  <- orchestrator/*.py (unchanged handlers + runtime_config etc.)
#   bin/ffmpeg,ffprobe <- the exact static binaries from the AWS Lambda ffmpeg layer
#   requirements.txt   <- flattened, pinned requirements-azure.txt
# Deploy with: (cd azure-functions && func azure functionapp publish <app> --python)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FA="$ROOT/azure-functions"

rm -rf "$FA/orchestrator_src" "$FA/bin"
mkdir -p "$FA/orchestrator_src" "$FA/bin"
cp "$ROOT"/orchestrator/*.py "$FA/orchestrator_src/"

LAYER="$ROOT/aws-infra/.ffmpeg-layer/bin"
if [[ -x "$LAYER/ffmpeg" && -x "$LAYER/ffprobe" ]]; then
  cp "$LAYER/ffmpeg" "$LAYER/ffprobe" "$FA/bin/"
else
  echo "WARNING: $LAYER missing; quality-checker needs ffmpeg in bin/ (FFMPEG_PATH)" >&2
fi

{
  echo "# Generated by scripts/build_functions.sh from requirements-azure.txt (do not edit by hand)."
  grep -hvE '^\s*(#|-r|$)' "$ROOT/requirements-lambda.txt" "$ROOT/requirements-azure.txt"
} > "$FA/requirements.txt"

echo "built $FA: $(ls "$FA/orchestrator_src" | wc -l | tr -d ' ') modules, bin: $(ls "$FA/bin" | tr '\n' ' ')"
